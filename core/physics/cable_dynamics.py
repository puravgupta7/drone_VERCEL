"""
High-Altitude Cryogenic Cable Rigidity & Hysteresis Modeling.
Simulates the dramatic increase in torsional and flexural stiffness of gimbal
wiring harnesses at extreme sub-zero temperatures (-40°C), including nonlinear
Bouc-Wen hysteresis, stiction, and material comparison (PVC, PUR, Silicone, PTFE).
"""

import math
from dataclasses import dataclass
from typing import Dict, Tuple


@dataclass
class CableMaterialProperties:
    name: str
    nominal_elastic_modulus_gpa: float  # E at +20°C
    glass_transition_temp_c: float     # T_g
    thermal_stiffening_exponent: float  # Alpha factor
    internal_hysteresis_ratio: float   # Ratio of hysteretic restoring torque to linear torque
    mil_spec_rated_low_temp_c: float   # Minimum certified operating temperature


# Database of cable jacketing materials used in aerospace/defense gimbals
CABLE_MATERIALS: Dict[str, CableMaterialProperties] = {
    "standard_pvc": CableMaterialProperties(
        name="Commercial PVC Jacket",
        nominal_elastic_modulus_gpa=3.0,
        glass_transition_temp_c=-10.0,
        thermal_stiffening_exponent=3.2,
        internal_hysteresis_ratio=0.65,
        mil_spec_rated_low_temp_c=-15.0
    ),
    "polyurethane_pur": CableMaterialProperties(
        name="Industrial Polyurethane (PUR)",
        nominal_elastic_modulus_gpa=0.08,
        glass_transition_temp_c=-35.0,
        thermal_stiffening_exponent=2.1,
        internal_hysteresis_ratio=0.45,
        mil_spec_rated_low_temp_c=-40.0
    ),
    "aerospace_silicone": CableMaterialProperties(
        name="Aerospace Fluorosilicone",
        nominal_elastic_modulus_gpa=0.02,
        glass_transition_temp_c=-65.0,
        thermal_stiffening_exponent=0.85,
        internal_hysteresis_ratio=0.20,
        mil_spec_rated_low_temp_c=-55.0
    ),
    "mil_spec_ptfe": CableMaterialProperties(
        name="MIL-W-22759/ETFE-PTFE (Optimized)",
        nominal_elastic_modulus_gpa=0.50,
        glass_transition_temp_c=-80.0,
        thermal_stiffening_exponent=0.45,
        internal_hysteresis_ratio=0.15,
        mil_spec_rated_low_temp_c=-65.0
    )
}


class CableHysteresisModel:
    """
    Bouc-Wen model of cable harness hysteresis & temperature-dependent restoring torque:
    T_cable = K_linear(T) * theta + K_hyst(T) * z
    where dz/dt = dtheta/dt * (1 - |z/z_max|^n * (beta * sign(dtheta/dt * z) + gamma))
    """

    def __init__(self, material_key: str = "standard_pvc", harness_length_m: float = 0.45, diameter_mm: float = 14.0):
        self.material_key = material_key
        self.props = CABLE_MATERIALS.get(material_key, CABLE_MATERIALS["standard_pvc"])
        self.harness_length_m = harness_length_m
        self.diameter_mm = diameter_mm
        
        # Internal Bouc-Wen state variable for hysteresis (radians displacement equivalent)
        self.z_hyst_az = 0.0
        self.z_hyst_el = 0.0
        
        # Bouc-Wen parameters
        self.z_max = 0.05  # rad (yield threshold)
        self.bw_beta = 0.5
        self.bw_gamma = 0.5
        self.bw_n = 2.0

    def compute_stiffness_multiplier(self, temperature_c: float) -> float:
        """
        Computes the ratio K(T) / K(+20°C).
        Below the glass transition temperature T_g, rigidity increases exponentially.
        """
        t_ref = 20.0
        delta_t = max(0.0, t_ref - temperature_c)
        
        # Base stiffening function
        alpha = self.props.thermal_stiffening_exponent
        multiplier = 1.0 + (delta_t / 40.0) ** alpha
        
        # Glass transition penalty
        if temperature_c < self.props.glass_transition_temp_c:
            embrittlement = (self.props.glass_transition_temp_c - temperature_c) * 0.4
            multiplier += embrittlement ** 1.8
            
        return multiplier

    def compute_restoring_torque(
        self,
        angle_rad: float,
        angular_vel_rad_s: float,
        temperature_c: float,
        dt: float,
        axis: str = "az"
    ) -> Tuple[float, float]:
        """
        Computes total resistive torque generated by the stiffened cable harness.
        
        Returns:
            Tuple of (total_restoring_torque_nm, stiffness_multiplier).
        """
        stiff_mult = self.compute_stiffness_multiplier(temperature_c)
        
        # Base baseline linear torsional stiffness at +20°C in N*m/rad
        # Baseline: ~0.8 N*m/rad for standard bundle at room temp
        k_base = 0.85 * (self.diameter_mm / 14.0) ** 3 / (self.harness_length_m / 0.45)
        
        k_linear = k_base * stiff_mult
        k_hyst = k_linear * self.props.internal_hysteresis_ratio
        
        # Update Bouc-Wen state
        z_state = self.z_hyst_az if axis == "az" else self.z_hyst_el
        
        dz_dt = angular_vel_rad_s * (
            1.0 - math.pow(abs(z_state / self.z_max), self.bw_n) * (
                self.bw_beta * math.copysign(1.0, angular_vel_rad_s * z_state) + self.bw_gamma
            )
        )
        z_state_new = z_state + dz_dt * dt
        # Clamp state to physically realistic bounds
        z_state_new = max(-self.z_max * 1.5, min(self.z_max * 1.5, z_state_new))
        
        if axis == "az":
            self.z_hyst_az = z_state_new
        else:
            self.z_hyst_el = z_state_new
            
        # Total restoring torque (linear spring + hysteretic memory + viscous drag)
        viscous_drag = 0.05 * stiff_mult * angular_vel_rad_s
        total_torque = (k_linear * angle_rad) + (k_hyst * z_state_new) + viscous_drag
        
        return total_torque, stiff_mult

    def reset(self):
        self.z_hyst_az = 0.0
        self.z_hyst_el = 0.0
